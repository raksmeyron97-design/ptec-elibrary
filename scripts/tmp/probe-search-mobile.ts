import { chromium, devices } from "@playwright/test";
import { makeLargeTestPdf } from "../../e2e/utils/pdf";
import { startPdfServer } from "../../e2e/utils/pdf-server";
import { installSeededReaderSession } from "../../e2e/utils/auth";
import dotenv from "dotenv";
dotenv.config({ path: ".env.local", quiet: true });

(async () => {
  const pdf = makeLargeTestPdf({ pages: 500, bytesPerPage: 8 * 1024, label: "PTEC search" });
  const server = await startPdfServer(pdf);
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices["Pixel 5"], baseURL: "http://localhost:3100" });
  const page = await ctx.newPage();
  page.on("pageerror", (e) => console.log("[pageerror]", e.message.slice(0, 120)));
  await page.addInitScript(`try { for (const k of Object.keys(localStorage)) if (k.startsWith("ebook:")) localStorage.removeItem(k); } catch {}`);
  await installSeededReaderSession(page, { email: "staff@ptec.local", origin: "http://localhost:3100" });
  await page.route("**/api/books/*/file*", (r) => r.continue({ url: server.url }));
  await page.goto("/books/foundations-of-education/read");
  await page.locator(".react-pdf__Page canvas").first().waitFor({ timeout: 60000 });
  await page.keyboard.press("Escape");
  const ind = () => page.locator('[data-reader-hud] button[aria-label^="Page "]:visible').first().getAttribute("aria-label");
  console.log("start", await ind());
  await page.keyboard.press("Shift");
  await page.keyboard.press("/");
  const input = page.getByRole("searchbox", { name: /search this book/i });
  await input.fill("page 4");
  await page.waitForTimeout(4000);
  console.log("after 'page 4'", await ind(), "| hits", await page.locator("text=/\\d+ of \\d+/").first().textContent().catch(() => null));
  await input.fill("page 431");
  await page.waitForTimeout(15000);
  console.log("after 'page 431'", await ind(), "| hits", await page.locator("text=/\\d+ of \\d+/").first().textContent().catch(() => null));
  console.log("mounted", await page.$$eval("[data-page]", (e) => e.map((x) => x.getAttribute("data-page")).join(",")));
  console.log("scroll", await page.evaluate(() => { const el = document.querySelector(".reader-viewport") as HTMLElement; return { top: el?.scrollTop, h: el?.scrollHeight, c: el?.clientHeight }; }));
  await browser.close();
  await server.close();
})();
